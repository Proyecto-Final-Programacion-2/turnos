CREATE TABLE reservation_process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    external_patient_id VARCHAR(100) NOT NULL,
    hold_id VARCHAR(255) NOT NULL,
    reservation_process_id VARCHAR(255) NOT NULL,
    reservation_id BIGINT,
    professional_id BIGINT NOT NULL,
    appointment_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(32) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_reservation_process_owner
        FOREIGN KEY (owner_user_id) REFERENCES jhi_user (id),
    CONSTRAINT uk_reservation_process_hold_id UNIQUE (hold_id),
    CONSTRAINT uk_reservation_process_external_id UNIQUE (reservation_process_id),
    CONSTRAINT uk_reservation_process_reservation_id UNIQUE (reservation_id),
    CONSTRAINT ck_reservation_process_slot CHECK (end_time > start_time)
);

-- Aceleran consultas por usuario y recuperacion de procesos pendientes/vencidos.
CREATE INDEX idx_reservation_process_owner ON reservation_process (owner_user_id);
CREATE INDEX idx_reservation_process_status_expiry ON reservation_process (status, expires_at);
