-- Cuentas finales de la aplicacion, almacenadas solo en la base propia de Turnos.
CREATE TABLE jhi_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(50) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(254) NOT NULL,
    activated BOOLEAN NOT NULL DEFAULT TRUE,
    image_url VARCHAR(256),
    lang_key VARCHAR(10) NOT NULL DEFAULT 'es',
    created_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_jhi_user_login UNIQUE (login),
    CONSTRAINT uk_jhi_user_email UNIQUE (email)
);

-- Una cuenta puede tener varias autoridades; el alta publica solo asigna ROLE_USER.
CREATE TABLE jhi_user_authority (
    user_id BIGINT NOT NULL,
    authority_name VARCHAR(50) NOT NULL,
    CONSTRAINT pk_jhi_user_authority PRIMARY KEY (user_id, authority_name),
    CONSTRAINT fk_jhi_user_authority_user
        FOREIGN KEY (user_id) REFERENCES jhi_user (id) ON DELETE CASCADE
);
